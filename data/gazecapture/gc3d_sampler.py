import numpy as np

class GC3D_Sampler:
    def __init__(self, valid_ids, D_roster, D_gt, n_per_person=3000,
                 split='train',
                 bin_args={}, target_N=None,
                 pitch_cid=None, yaw_cid=None):
        '''
        "VAL" mode: population_per_person set to 0.
        D: dict. The data from "gt*.npy"
            ===[key list]===
            'fn' - processed_entry['file_name']
            ---GT---
            'gaze' - processed_entry['normalized_gaze_direction'])
            'gaze_L' - processed_entry['normalized_gaze_direction_left'])
            'gaze_R' - processed_entry['normalized_gaze_direction_right'])
            'head_pose'
            ---GT quantized---
            pitch_cid
            yaw_cid
            cam_cid
            pitch_nbins
            yaw_nbins
            bin_size
            pitch_bias
            ---IDs---
            start_ids: Dict. first id (value) for each person (key)
        D_roster: dict. stores the sample ID (value) for each person (key)
            * generated by GC3D dataset class
        D_pop: dict. The data from "train/val.npy", storing subject ID list and corresponding population (# of samples).
            ===[key list]===
            'id': list[str]
            'polulation': list[int]
        n_per_person: output sample # per person per epoch.
        '''
        self.D = D_gt
        self.D_roster = D_roster
        self.valid_ids = valid_ids
        self.n_per_person = n_per_person
        self.split = split

        self.target_N = target_N
        if len(bin_args) > 0 and self.target_N is not None:
            self.bin = True
            self.nbins_pitch = bin_args['pitch_nbins']
            self.nbins_yaw = bin_args['yaw_nbins']
            self.pitch_bias = bin_args['pitch_bias']
            self.bin_size = bin_args.get('bin_size', 4)

            self.yaw_cid = yaw_cid

            if split == 'train':
                self.n_per_bin = self.target_N // self.nbins_yaw
            else:
                self.n_per_bin = self.target_N // (self.nbins_yaw - 2)
            self.gt_gaze = self.D['gaze']
        else: self.bin = False

    def sample(self, same_person_sample_num=1, shuffle=True, debug=False):
        '''
        shuffle & sample.
        same_person_sample_num: if > 1, ensures an MB contains at least ~ samples of the same subject.
            * should be divisible by population_per_person.
        '''
        if debug:
            import time
            ti = time.time()
        
        if self.n_per_person == 0: return self.valid_ids
        ssl = same_person_sample_num > 1
        if ssl:
            cliques = []
        
        if self.bin:
            H_yaw = [0 for _ in range(self.nbins_yaw)] # histogram-1D
            bins_yaw = [[] for _ in range(self.nbins_yaw)]

        new_id_list = []
        for subject, value in self.D_roster.items():
            person_pop = len(value)
            n_repeat = self.n_per_person // person_pop
            n_tail = self.n_per_person % person_pop
            sampled_bin = []
            for _ in range(n_repeat):
                sampled_bin = np.append(sampled_bin, self.D_roster[subject])
            sampled_bin = np.append(sampled_bin,
                                    np.random.permutation(self.D_roster[subject])[:n_tail])
            if ssl:
                sampled_bin = np.random.permutation(sampled_bin)
                for i in range(0, self.target_N, same_person_sample_num):
                    cliques.append(sampled_bin[i:i+same_person_sample_num])
            else:
                new_id_list = np.append(new_id_list, sampled_bin)

        new_id_list = new_id_list.astype(int)
        if self.bin:
            for i in new_id_list:
                if self.yaw_cid is not None:
                    yaw_cid = self.yaw_cid[i]
                else:
                    gaze_yaw = self.gt_gaze[i][1]
                    yaw_cid = int(np.clip(((gaze_yaw * 180 / np.pi) // self.bin_size) + (self.nbins_yaw // 2 + 0.5), 0, self.nbins_yaw-1))
                H_yaw[yaw_cid] += 1
                bins_yaw[yaw_cid].append(i)

            if debug: print(H_yaw)
            
            # draw samples, # = target_N
            id_list_bin = []
            for i in range(self.nbins_yaw):
                if self.split != 'train' and (i == 0 or i == self.nbins_yaw-1): continue
                n_repeat = self.n_per_bin // H_yaw[i]
                n_tail = self.n_per_bin % H_yaw[i]
                for _ in range(n_repeat):
                    id_list_bin = np.append(id_list_bin, bins_yaw[i])
                id_list_bin = np.append(id_list_bin,
                                        np.random.permutation(bins_yaw[i])[:n_tail])
            new_id_list = id_list_bin

        if shuffle:
            if ssl:
                indices = np.random.permutation(len(cliques))
                for i in indices:
                    new_id_list.extend(cliques[i])
            else:
                new_id_list = np.random.permutation(new_id_list)

        if debug:
            to = time.time()
            print("[GC3D_sampler] time =", to-ti)

        return np.array(new_id_list)

