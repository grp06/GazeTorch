import numpy as np

class GazeGene_2D_Sampler:
    def __init__(self, D, id_list=None, split='train',
        bin_args={}, # nbins_pitch=17, nbins_yaw=17, pitch_bias=-8, bin_size=4,
        pitch_cid=None, yaw_cid=None,
        target_N=None):
        '''
        D is a dict generated by gaze360 data (e.g. double_eye_val.npy)
        id_list: predefined valid id list. If None, the sampler calculates it.
        split: if not 'train', then discard the samples from leftmost and rightmost bins.
        The following attributes are used only if id_list=None:
        * cams: list of cameras to be included. If None, use data from all cameras.
        * hybrid mode: (deprecated) neglect those with pitch_cid <= 2.
        * target_N
            * if given, specifies len of sample()'s output
            * if None, make the bin distribution follow Gaussian
        '''
        self.D = D
        self.n = len(D['fn'])
        self.nbins_pitch = bin_args['pitch_nbins']
        self.nbins_yaw = bin_args['yaw_nbins']
        self.pitch_bias = bin_args['pitch_bias']
        self.bin_size = bin_args.get('bin_size', 4)
        self.split = split

        self.threshold = 2 # +- threshold in N(0,1)
        self.bins = []
        for i in range(self.nbins_pitch):
            self.bins.append([])
            for _ in range(self.nbins_yaw):
                self.bins[i].append([])
        self.actual_bin_pop = np.zeros((self.nbins_pitch, self.nbins_yaw), int)

        if id_list is None:
            self.id_list = []
            for i in range(self.n):
                if pitch_cid is None and yaw_cid is None:
                    if split!='train' and (D['pitch_cid'][i]==0 or D['pitch_cid'][i]==self.nbins_pitch-1 or \
                        D['yaw_cid'][i]==0 or D['yaw_cid'][i]==self.nbins_yaw-1): # only val & test mode skips first and last bin
                        continue
                    pitch = D['pitch_cid'][i]
                    yaw = D['yaw_cid'][i]
                else:
                    if split!='train' and (pitch_cid==0 or pitch_cid==self.nbins_pitch-1 or \
                        yaw_cid==0 or yaw_cid==self.nbins_yaw-1): # only val & test mode skips first and last bin
                        continue
                    pitch = pitch_cid[i]
                    yaw = yaw_cid[i]

                self.id_list.append(i)
                self.bins[pitch][yaw].append(i)
                self.actual_bin_pop[pitch, yaw] += 1
        else:
            self.id_list = []
            for i in id_list:
                if pitch_cid is None and yaw_cid is None:
                    if split!='train' and (D['pitch_cid'][i]==0 or D['pitch_cid'][i]==self.nbins_pitch-1 or \
                            D['yaw_cid'][i]==0 or D['yaw_cid'][i]==self.nbins_yaw-1): # only val & test mode skips first and last bin
                            continue
                    pitch = D['pitch_cid'][i]
                    yaw = D['yaw_cid'][i]
                else:
                    if split!='train' and (pitch_cid[i]==0 or pitch_cid[i]==self.nbins_pitch-1 or \
                        yaw_cid[i]==0 or yaw_cid[i]==self.nbins_yaw-1): # only val & test mode skips first and last bin
                        continue
                    pitch = int(pitch_cid[i])
                    yaw = int(yaw_cid[i])
                self.id_list.append(i)
                self.bins[pitch][yaw].append(i)
                self.actual_bin_pop[pitch, yaw] += 1

        self.population = len(self.id_list)
        # self.plot_histogram()
        if target_N is None:
            self.quote_bin_pop = self.bin_quote_gaussian()
        else:
            self.quote_bin_pop = self.bin_quote(target_N)
        self.population_quote = np.sum(self.quote_bin_pop)
        print("[Dataset.sampler]Initialized. Len = ", self.population_quote)

    def _freq_1d(self, n_bins): # deprecated
        import scipy.stats as S
        cdf = S.norm.cdf
        interval = self.threshold * 2 / n_bins

        bins = [0 for _ in range(n_bins)]
        it = range(1, n_bins - 1) if self.split != 'train' else range(n_bins)

        for i in it:
            x1 = -self.threshold + interval*i
            x2 = -self.threshold + interval*(i+1)
            bins[i] = (cdf(x2) - cdf(x1))
        return bins

    def bin_quote_gaussian(self): # deprecated
        # get histogram (actual bin sizes) & ideal bin sizes

        # |x|+|y|
        # freq_pitch = self._freq_1d(self.nbins_pitch)
        # freq_yaw = self._freq_1d(self.nbins_yaw)
        #
        # freq = np.dot(np.array(freq_pitch).reshape((self.nbins_pitch, 1)),
        #               np.array(freq_yaw).reshape((1, self.nbins_yaw)))
        # freq = freq / np.sum(freq) * self.population

        # max(x,y)
        import scipy.stats as S
        pdf = S.norm.pdf
        freq = np.zeros((self.nbins_pitch, self.nbins_yaw))

        n_half_pitch = self.nbins_pitch // 2
        n_half_yaw = self.nbins_yaw // 2

        for i in range(self.nbins_pitch):
            for j in range(self.nbins_yaw):
                if i==0 or i==self.nbins_pitch-1 or j==0 or j==self.nbins_yaw-1:
                    freq[i,j] = 0.01
                else:
                    freq[i,j] = pdf(max(np.abs(i - n_half_pitch) / n_half_pitch,
                        np.abs(j - n_half_yaw) / n_half_yaw) * self.threshold)

        freq = freq / np.sum(freq) * self.population

        return freq.astype(int)
    
    def bin_quote(self, target_N):
        if self.split == 'train':
            n_each = target_N // (self.nbins_pitch * self.nbins_yaw)
            freq = np.ones((self.nbins_pitch, self.nbins_yaw), dtype=int) * n_each
        else:
            freq = np.zeros((self.nbins_pitch, self.nbins_yaw), dtype=int)
            n_each = target_N // ((self.nbins_pitch - 2) * (self.nbins_yaw - 2))
            freq[1:-1, 1:-1] = n_each
        return freq

    def sample(self):
        new_id_list = []
        for pitch in range(self.nbins_pitch):
            for yaw in range(self.nbins_yaw):
                if self.quote_bin_pop[pitch, yaw]==0 or self.actual_bin_pop[pitch, yaw]==0:
                    continue
                n_repeat = self.quote_bin_pop[pitch, yaw] // self.actual_bin_pop[pitch, yaw]
                n_tail = self.quote_bin_pop[pitch, yaw] % self.actual_bin_pop[pitch, yaw]
                sampled_bin = []
                for i in range(n_repeat):
                    sampled_bin = np.append(sampled_bin, self.bins[pitch][yaw])
                sampled_bin = np.append(sampled_bin,
                                        np.random.permutation(self.bins[pitch][yaw])[:n_tail])
                new_id_list = np.append(new_id_list, sampled_bin)

        return np.random.permutation(new_id_list).astype(int)